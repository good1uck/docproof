// Extract "claims" from a Markdown file and turn them into Kane CLI _test.md files.
//
// A claim is an ordered list placed right after a marker comment:
//
//   <!-- docproof:claim id=split-basic -->
//   1. Open the app.
//   2. Type `120` in **Bill** and `4` in **People**.
//   3. You should see **Each person pays $34.50**.
//
// Optional marker attributes: path=?bill=80 (appended to the app URL for "Open the app").

const MARKER = /<!--\s*docproof:claim\s+([^>]*?)\s*-->/;
const LIST_ITEM = /^\s*(\d+)[.)]\s+(.*)$/;

export function parseAttrs(text) {
  const attrs = {};
  for (const m of text.matchAll(/([a-zA-Z_-]+)=("([^"]*)"|'([^']*)'|(\S+))/g)) {
    attrs[m[1]] = m[3] ?? m[4] ?? m[5];
  }
  return attrs;
}

/** Remove inline Markdown so Kane sees plain English. */
export function plain(text) {
  return text
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/(\*\*|__)(.+?)\1/g, '"$2"')
    .replace(/`([^`]+)`/g, '"$1"')
    .replace(/(^|\W)[*_](\S[^*_]*?)[*_](?=\W|$)/g, '$1$2')
    .replace(/""/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * @param {string} markdown
 * @param {string} [source] file name, for error messages and line refs
 * @returns {{id:string, title:string, path:string, line:number, steps:string[], source:string}[]}
 */
export function extractClaims(markdown, source = 'README.md') {
  const lines = markdown.split(/\r?\n/);
  const claims = [];
  const seen = new Set();
  let heading = '';
  let inFence = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    if (inFence) continue;
    const h = line.match(/^#{1,6}\s+(.*)$/);
    if (h) heading = plain(h[1]);
    const m = line.match(MARKER);
    if (!m) continue;

    const attrs = parseAttrs(m[1]);
    if (!attrs.id || !/^[a-z0-9][a-z0-9_-]*$/i.test(attrs.id)) {
      throw new Error(`${source}:${i + 1}: docproof marker needs id=<letters, digits, - or _>`);
    }
    if (seen.has(attrs.id)) throw new Error(`${source}:${i + 1}: duplicate claim id "${attrs.id}"`);
    seen.add(attrs.id);

    const steps = [];
    let j = i + 1;
    while (j < lines.length && lines[j].trim() === '') j++;
    for (; j < lines.length; j++) {
      const item = lines[j].match(LIST_ITEM);
      if (item) { steps.push(item[2]); continue; }
      if (steps.length && /^\s{2,}\S/.test(lines[j])) { steps[steps.length - 1] += ' ' + lines[j].trim(); continue; }
      break;
    }
    if (!steps.length) throw new Error(`${source}:${i + 1}: claim "${attrs.id}" has no numbered steps after it`);

    claims.push({
      id: attrs.id,
      title: attrs.title || heading || attrs.id,
      path: attrs.path || '',
      line: i + 1,
      steps: steps.map(plain),
      source,
    });
  }
  return claims;
}

/** Turn one README step into a Kane objective. */
export function toObjective(step, claim) {
  let s = step.replace(/\.$/, '');
  if (/^(open|go to|visit|load)\s+(the\s+)?(app|page|site|home ?page)\b/i.test(s)) {
    return `Open {{app_url}}${claim.path} and wait for the page to finish loading.`;
  }
  const see = s.match(/^(?:then\s+)?(?:you\s+)?(?:should\s+)?(?:will\s+)?(?:see|shows?|displays?)\s+(.*)$/i);
  if (see) return `Verify the page shows ${see[1]}.`;
  if (/^(verify|assert|check|confirm)\b/i.test(s)) return s + '.';
  return s + '.';
}

function shorten(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  return cut.slice(0, Math.max(cut.lastIndexOf(' '), 20)).replace(/[\s,;:]+$/, '') + '…';
}

/** Render a claim as a Kane CLI _test.md file. */
export function toTestMd(claim) {
  const steps = claim.steps.map((step, n) => {
    const objective = toObjective(step, claim);
    const short = shorten(step.replace(/\.$/, ''), 60);
    return `## ${n + 1}. ${short}\n${objective}\n`;
  });
  return [
    '---',
    'mode: testing',
    'tags: [docproof]',
    'max_steps: 20',
    '---',
    '',
    `# ${claim.title}`,
    '',
    `<!-- Generated by docproof from ${claim.source} (claim id=${claim.id}). Edit the README, not this file. -->`,
    '',
    ...steps,
  ].join('\n');
}
